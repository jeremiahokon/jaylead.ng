/**
 * Copy guardrails (brief 2 and 14.1). Fails when an em dash appears anywhere
 * in the source, docs or rendered HTML, or when a banned phrase appears in
 * the rendered pages or the seed content. Run after `next build`:
 *   pnpm check:copy
 */
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

function walk(dir, exts, out = []) {
  for (const name of readdirSync(dir)) {
    if (name === 'node_modules' || (name.startsWith('.') && name !== '.next'))
      continue;
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) walk(p, exts, out);
    else if (exts.some((e) => p.endsWith(e))) out.push(p);
  }
  return out;
}

const banned = [
  [
    /\bguarantee(d|s)?\b/i,
    (ctx) =>
      !/\bnot\b[^.]{0,40}guaranteed|\bneither\b[^.]{0,60}guaranteed|\bno guarantee|aren’t guaranteed|isn’t guaranteed|are not guaranteed|is not guaranteed|guaranteed\?|“guaranteed”|"guaranteed"|guarantee claim|guaranteed deposit/i.test(
        ctx
      ),
  ],
  [/100%/, () => true],
  [
    /risk[- ]free/i,
    (ctx) =>
      !/not (mean )?risk-free|isn’t risk-free|neither is risk-free|“risk-free”|"risk-free"/i.test(
        ctx
      ),
  ],
  [/\bno risk\b/i, (ctx) => !/“no risk”|"no risk"/.test(ctx)],
  [/sure returns/i, (ctx) => !/“sure returns”|"sure returns"/.test(ctx)],
  [/limited slots|only \d+ left|act now/i, (ctx) => !/“|"/.test(ctx)],
  [/\blicensed\b/i, (ctx) => !/“licensed”|"licensed"|licensed”/.test(ctx)],
  [/\bpoultry\b|\beggs?\b|\begg income\b/i, (ctx) => !/“|"/.test(ctx)],
  [/\bTenera\b/, (ctx) => !/“Tenera”|"Tenera"/.test(ctx)],
  [/150 years|50 to 100 years/i, (ctx) => !/“150 years”|"150 years"/.test(ctx)],
];

const EM = String.fromCharCode(0x2014);
const problems = [];

// 1. Em dashes: nowhere in our own files.
for (const f of walk(root, [
  '.ts',
  '.tsx',
  '.mts',
  '.mjs',
  '.css',
  '.md',
  '.sh',
  '.py',
  '.html',
])) {
  // AGENTS.md is regenerated by `next dev`; the brief and playbooks are inputs, not site copy.
  if (
    f.includes('/.next/') ||
    f.includes('/jaylead_ng/') ||
    f.endsWith('jaylead_ng-site-build-brief.md') ||
    f.endsWith('AGENTS.md') ||
    f.includes('/.claude/') ||
    f.includes('/playbook/')
  )
    continue;
  const text = readFileSync(f, 'utf8');
  text.split('\n').forEach((line, i) => {
    if (line.includes(EM))
      problems.push(`${relative(root, f)}:${i + 1}: em dash`);
  });
}

// 2. Banned phrases in what visitors and crawlers read: rendered HTML, llms.txt, and seed copy.
const rendered = walk(join(root, '.next/server/app'), [
  '.html',
  '.body',
]).filter((f) => !f.includes('/studio') && !f.includes('.segments'));
const seeds = walk(join(root, 'src/data'), ['.ts']);
for (const f of [...rendered, ...seeds]) {
  // Visible text and JSON-LD only: styles, scripts and markup are not copy.
  const text = readFileSync(f, 'utf8')
    .replace(/<style[\s\S]*?<\/style>/g, ' ')
    .replace(/<script[\s\S]*?<\/script>/g, (m) =>
      m.includes('ld+json') ? m.replace(/<[^>]+>/g, ' ') : ' '
    )
    .replace(/<[^>]+>/g, ' ')
    .replace(/&#x27;|&#39;/g, "'")
    .replace(/&quot;/g, '"');
  for (const [re, isViolation] of banned) {
    const g = new RegExp(
      re.source,
      re.flags.includes('g') ? re.flags : `${re.flags}g`
    );
    for (const m of text.matchAll(g)) {
      const ctx = text.slice(Math.max(0, m.index - 60), m.index + 60);
      if (isViolation(ctx))
        problems.push(
          `${relative(root, f)}: "${m[0]}" in …${ctx.replace(/\s+/g, ' ')}…`
        );
    }
  }
}

if (problems.length) {
  console.error(
    `Copy check failed (${problems.length}):\n${[...new Set(problems)].slice(0, 80).join('\n')}`
  );
  process.exit(1);
}
console.log(
  `Copy check passed: ${rendered.length} rendered files and ${seeds.length} seed files clean, no em dashes.`
);
